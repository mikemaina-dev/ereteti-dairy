# Ereteti Dairy Sacco Website

A PHP and MySQL website for Ereteti Dairy Sacco: home, about, routes,
contact, membership application and milk deliveries pages.

## How to run it
1. Install XAMPP and start Apache and MySQL.
2. Copy this folder into `C:\xampp\htdocs\ereteti-dairy`.
3. Open http://localhost/phpmyadmin, click SQL, paste the contents of
   `database.sql` and click Go.
4. Open http://localhost/ereteti-dairy/ in your browser.

